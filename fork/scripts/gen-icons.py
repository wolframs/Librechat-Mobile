#!/usr/bin/env python3
"""Turn the vendored Lucide SVGs into Compose ImageVectors.

    fork/scripts/gen-icons.py            rewrite ForkIcons.kt from fork/icons/lucide/*.svg
    fork/scripts/gen-icons.py --add NAME [NAME...]   fetch more icons at the pinned version first

The SVGs are vendored so a build needs no network. Lucide draws on a 24 x 24 grid with round
stroked lines and no fills; this script supports exactly the elements those files use.
"""
import re
import sys
import urllib.request
from pathlib import Path
from xml.etree import ElementTree

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "fork" / "icons" / "lucide"
TARGET = ROOT / "fork/src/commonMain/kotlin/com/garfiec/librechat/fork/icons/ForkIcons.kt"
VERSION = "1.72.0"
RAW = f"https://raw.githubusercontent.com/lucide-icons/lucide/{VERSION}/icons/{{name}}.svg"


def number(value: float) -> str:
    return f"{value:.3f}".rstrip("0").rstrip(".")


def circle(el) -> str:
    cx, cy, r = (float(el.get(k)) for k in ("cx", "cy", "r"))
    return f"M{number(cx - r)} {number(cy)}a{number(r)} {number(r)} 0 1 0 {number(2 * r)} 0a{number(r)} {number(r)} 0 1 0 {number(-2 * r)} 0"


def rect(el) -> str:
    x, y, w, h = (float(el.get(k, 0)) for k in ("x", "y", "width", "height"))
    rx = float(el.get("rx", el.get("ry", 0)))
    ry = float(el.get("ry", el.get("rx", 0)))
    if rx == 0 and ry == 0:
        return f"M{number(x)} {number(y)}h{number(w)}v{number(h)}h{number(-w)}z"
    a = f"a{number(rx)} {number(ry)} 0 0 1"
    return (
        f"M{number(x + rx)} {number(y)}h{number(w - 2 * rx)}{a} {number(rx)} {number(ry)}"
        f"v{number(h - 2 * ry)}{a} {number(-rx)} {number(ry)}h{number(-(w - 2 * rx))}"
        f"{a} {number(-rx)} {number(-ry)}v{number(-(h - 2 * ry))}{a} {number(rx)} {number(-ry)}z"
    )


def paths(svg: Path) -> list[str]:
    out = []
    for el in ElementTree.parse(svg).getroot():
        tag = el.tag.split("}")[-1]
        if tag == "path":
            out.append(el.get("d"))
        elif tag == "circle":
            out.append(circle(el))
        elif tag == "rect":
            out.append(rect(el))
        else:
            raise SystemExit(f"{svg.name}: unsupported element <{tag}>")
    return out


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in re.split(r"[-_]", name))


def generate() -> None:
    icons = sorted(SOURCE.glob("*.svg"))
    body = []
    for svg in icons:
        args = ",\n".join(f'            "{d}"' for d in paths(svg))
        body.append(f"    val {pascal(svg.stem)}: ImageVector by lazy {{\n        lucide(\n            \"{pascal(svg.stem)}\",\n{args},\n        )\n    }}")
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(
        "// Generated by fork/scripts/gen-icons.py from fork/icons/lucide (Lucide "
        + VERSION
        + ", ISC license). Do not edit.\n"
        "@file:Suppress(\"MaxLineLength\", \"LargeClass\")\n\n"
        "package com.garfiec.librechat.fork.icons\n\n"
        "import androidx.compose.ui.graphics.Color\n"
        "import androidx.compose.ui.graphics.SolidColor\n"
        "import androidx.compose.ui.graphics.StrokeCap\n"
        "import androidx.compose.ui.graphics.StrokeJoin\n"
        "import androidx.compose.ui.graphics.vector.ImageVector\n"
        "import androidx.compose.ui.graphics.vector.addPathNodes\n"
        "import androidx.compose.ui.unit.dp\n\n"
        "/** The fork's line icons. An `Icon` tints them, so the stroke colour here is only a placeholder. */\n"
        "object ForkIcons {\n" + "\n\n".join(body) + "\n}\n\n"
        "private const val GRID = 24f\n"
        "private const val STROKE = 1.75f\n\n"
        "private fun lucide(name: String, vararg paths: String): ImageVector =\n"
        "    ImageVector.Builder(name, GRID.dp, GRID.dp, GRID, GRID).apply {\n"
        "        paths.forEach { data ->\n"
        "            addPath(\n"
        "                pathData = addPathNodes(data),\n"
        "                stroke = SolidColor(Color.Black),\n"
        "                strokeLineWidth = STROKE,\n"
        "                strokeLineCap = StrokeCap.Round,\n"
        "                strokeLineJoin = StrokeJoin.Round,\n"
        "            )\n"
        "        }\n"
        "    }.build()\n"
    )
    print(f"{len(icons)} icons -> {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    if "--add" in sys.argv:
        for name in sys.argv[sys.argv.index("--add") + 1:]:
            with urllib.request.urlopen(RAW.format(name=name)) as response:
                (SOURCE / f"{name}.svg").write_bytes(response.read())
            print(f"fetched {name}")
    generate()
